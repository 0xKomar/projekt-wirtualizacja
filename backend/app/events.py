import datetime as dt

from sqlalchemy import Engine, and_, or_, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.models import AlertRule, Device, Event, Reading


def as_utc(value: dt.datetime) -> dt.datetime:
    if value.tzinfo is None or value.utcoffset() is None:
        return value.replace(tzinfo=dt.timezone.utc)
    return value.astimezone(dt.timezone.utc)


def locked_device_query(*criteria):
    return select(Device).where(*criteria).with_for_update()


def locked_alert_rule_query(*criteria):
    return select(AlertRule).where(*criteria).with_for_update()


def persist_event_once(session: Session, event: Event) -> bool:
    try:
        with session.begin_nested():
            session.add(event)
            session.flush()
    except IntegrityError:
        duplicate = session.scalar(
            select(Event.id).where(Event.dedupe_key == event.dedupe_key)
        )
        if duplicate is None:
            raise
        return False
    return True


def add_threshold_events(
    session: Session,
    device_id: int,
    current_reading: Reading,
    continuity_limit_seconds: int,
) -> int:
    """Emit alerts from available readings; already-emitted events are immutable.

    A later-arriving backdated reading is stored, but does not revise or retract
    an event generated by an earlier evaluation.
    """
    rules = session.scalars(
        locked_alert_rule_query(
            AlertRule.enabled.is_(True),
            or_(AlertRule.device_id.is_(None), AlertRule.device_id == device_id),
        ).order_by(AlertRule.id)
    ).all()
    current_time = as_utc(current_reading.measured_at)
    created = 0

    for rule in rules:
        if current_reading.db_avg < rule.threshold_db:
            continue
        not_after_current = or_(
            Reading.measured_at < current_reading.measured_at,
            and_(
                Reading.measured_at == current_reading.measured_at,
                Reading.id <= current_reading.id,
            ),
        )
        last_below = session.scalar(
            select(Reading)
            .where(
                Reading.device_id == device_id,
                Reading.db_avg < rule.threshold_db,
                not_after_current,
            )
            .order_by(Reading.measured_at.desc(), Reading.id.desc())
            .limit(1)
        )
        statement = select(Reading).where(
            Reading.device_id == device_id,
            Reading.db_avg >= rule.threshold_db,
            not_after_current,
        )
        if last_below is not None:
            statement = statement.where(
                or_(
                    Reading.measured_at > last_below.measured_at,
                    and_(
                        Reading.measured_at == last_below.measured_at,
                        Reading.id > last_below.id,
                    ),
                )
            )
        high_readings = session.scalars(
            statement.order_by(Reading.measured_at, Reading.id)
        ).all()
        if not high_readings:
            continue

        high_times = [as_utc(reading.measured_at) for reading in high_readings]
        segment_start = 0
        for index, (earlier, later) in enumerate(zip(high_times, high_times[1:]), 1):
            if (later - earlier).total_seconds() > continuity_limit_seconds:
                segment_start = index
        first_high = high_times[segment_start]
        if (current_time - first_high).total_seconds() < rule.min_duration_seconds:
            continue

        already_created = session.scalar(
            select(Event.id)
            .where(
                Event.device_id == device_id,
                Event.alert_rule_id == rule.id,
                Event.type == "noise_threshold",
                Event.started_at == first_high,
            )
            .limit(1)
        )
        if already_created is not None:
            continue

        event = Event(
            device_id=device_id,
            alert_rule_id=rule.id,
            type="noise_threshold",
            started_at=first_high,
            description=(
                f"Average reading stayed at or above {rule.threshold_db:g} "
                f"for at least {rule.min_duration_seconds} seconds."
            ),
            dedupe_key=(
                f"noise:{device_id}:{rule.id}:"
                f"{first_high.isoformat(timespec='microseconds')}"
            ),
        )
        if persist_event_once(session, event):
            created += 1

    return created


def add_online_transition(session: Session, device_id: int, when: dt.datetime) -> bool:
    latest_status = session.scalar(
        select(Event)
        .where(
            Event.device_id == device_id,
            Event.type.in_(("device_offline", "device_online")),
        )
        .order_by(Event.started_at.desc(), Event.id.desc())
        .limit(1)
    )
    if latest_status is None or latest_status.type != "device_offline":
        return False
    event = Event(
        device_id=device_id,
        type="device_online",
        started_at=when,
        description="The device resumed sending readings.",
        dedupe_key=f"online:{device_id}:{latest_status.id}",
    )
    return persist_event_once(session, event)


def scan_offline_devices(
    engine: Engine,
    offline_after_seconds: int,
    now: dt.datetime | None = None,
) -> int:
    now = as_utc(now or dt.datetime.now(dt.timezone.utc))
    cutoff = now - dt.timedelta(seconds=offline_after_seconds)
    with Session(engine) as candidate_session:
        device_ids = candidate_session.scalars(
            select(Device.id).where(Device.last_seen_at.is_not(None))
        ).all()

    created = 0
    for device_id in device_ids:
        with Session(engine) as session:
            device = session.scalar(locked_device_query(Device.id == device_id))
            if device is None or device.last_seen_at is None:
                continue
            last_seen = as_utc(device.last_seen_at)
            if last_seen > cutoff:
                continue
            latest_status = session.scalar(
                select(Event)
                .where(
                    Event.device_id == device.id,
                    Event.type.in_(("device_offline", "device_online")),
                )
                .order_by(Event.started_at.desc(), Event.id.desc())
                .limit(1)
            )
            if latest_status is not None and latest_status.type == "device_offline":
                continue
            offline_started_at = last_seen + dt.timedelta(
                seconds=offline_after_seconds
            )
            event = Event(
                device_id=device.id,
                type="device_offline",
                started_at=offline_started_at,
                description=f"No reading received for {offline_after_seconds} seconds.",
                dedupe_key=(
                    f"offline:{device.id}:"
                    f"{last_seen.isoformat(timespec='microseconds')}"
                ),
            )
            if persist_event_once(session, event):
                session.commit()
                created += 1
    return created
